const CATALOG_URL = 'http://adlonline.tj/';
const body = document.body;
const langScreen = document.getElementById('langScreen');
const changeLang = document.getElementById('changeLang');
const themeToggle = document.getElementById('themeToggle');
const burger = document.getElementById('burger');
const nav = document.getElementById('nav');
const year = document.getElementById('year');
let currentLang = sessionStorage.getItem('adlLang') || 'ru';
let lastScrollY = window.scrollY;
let raf = null;
const revealEls = () => Array.from(document.querySelectorAll('.reveal'));
const activeSections = () => Array.from(document.querySelectorAll('.section, .footer'));

function applyLang(lang){
  currentLang = translations[lang] ? lang : 'ru';
  const dict = translations[currentLang];
  document.documentElement.lang = currentLang === 'tj' ? 'tg' : currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if(dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-gate]').forEach(el => {
    const key = el.dataset.gate;
    if(dict.gate[key]) el.textContent = dict.gate[key];
  });
  changeLang.textContent = currentLang.toUpperCase();
  sessionStorage.setItem('adlLang', currentLang);
}

function updateCatalogLinks(){
  document.querySelectorAll('a[href*="adonline.tj"], a[href*="adlonline.tj"]').forEach(a => {
    a.href = CATALOG_URL;
    a.target = '_blank';
    a.rel = 'noopener noreferrer';
  });
}

function showLanguage(){
  langScreen.classList.remove('hidden');
  body.classList.add('no-scroll');
  body.classList.remove('site-entered');
  closeMenu();
}

function forceReplay(el, className){
  el.classList.remove(className);
  void el.offsetWidth;
  el.classList.add(className);
}

function updateReveals(force = false){
  const y = window.scrollY || document.documentElement.scrollTop || 0;
  const direction = y >= lastScrollY ? 'down' : 'up';
  lastScrollY = y;
  body.dataset.scrollDir = direction;

  const vh = window.innerHeight || document.documentElement.clientHeight || 700;
  const isMobile = window.matchMedia('(max-width: 820px)').matches;
  const enterTop = vh * (isMobile ? 0.90 : 0.84);
  const enterBottom = vh * (isMobile ? 0.07 : 0.10);
  const resetTop = vh * (isMobile ? 1.22 : 1.12);
  const resetBottom = vh * (isMobile ? -0.22 : -0.14);

  revealEls().forEach((el, index) => {
    const rect = el.getBoundingClientRect();
    const visible = rect.top < enterTop && rect.bottom > enterBottom;
    const outside = rect.top > resetTop || rect.bottom < resetBottom;
    const delay = Math.min(index % (isMobile ? 6 : 8), isMobile ? 5 : 7) * (isMobile ? 72 : 76);
    el.style.setProperty('--delay', `${delay}ms`);
    el.dataset.scrollDir = direction;

    if(force || visible){
      if(force || !el.classList.contains('is-visible')){
        el.classList.remove('is-visible','mobile-visible','animate-again');
        void el.offsetWidth;
        el.classList.add('is-visible','animate-again');
        if(isMobile) el.classList.add('mobile-visible');
      }
    } else if(outside){
      el.classList.remove('is-visible','mobile-visible','animate-again');
    }
  });

  activeSections().forEach(section => {
    const rect = section.getBoundingClientRect();
    const active = rect.top < vh * 0.62 && rect.bottom > vh * 0.28;
    section.classList.toggle('section-active', active);
  });
}

function requestReveal(force = false){
  if(raf && !force) return;
  raf = requestAnimationFrame(() => {
    updateReveals(force);
    raf = null;
  });
}

function enter(lang){
  applyLang(lang);
  updateCatalogLinks();
  langScreen.classList.add('hidden');
  body.classList.remove('no-scroll');
  body.classList.add('site-entered');
  window.scrollTo({top: 0, behavior: 'auto'});
  setTimeout(() => requestReveal(true), 60);
  setTimeout(() => requestReveal(true), 420);
}

function applyTheme(theme){
  const light = theme === 'light';
  body.classList.toggle('theme-light', light);
  body.classList.toggle('theme-dark', !light);
  themeToggle.textContent = light ? '☾' : '☀';
  localStorage.setItem('adlTheme', light ? 'light' : 'dark');
}

function closeMenu(){
  nav.classList.remove('open');
  burger.classList.remove('open');
}

function initTouch(){
  document.querySelectorAll('a,button,.adv-card,.cat-card,.step-card,.catalog-panel a,.mock-list a,.showcase-card,.footer-social a').forEach(item => {
    item.addEventListener('touchstart', () => {
      item.classList.remove('tap-animate');
      void item.offsetWidth;
      item.classList.add('tap-animate');
    }, {passive:true});
    item.addEventListener('animationend', e => {
      if(e.animationName === 'tap' || e.animationName === 'mobileTap' || e.animationName === 'mobilePress') item.classList.remove('tap-animate');
    });
  });
}

function init(){
  if(year) year.textContent = new Date().getFullYear();
  applyTheme(localStorage.getItem('adlTheme') || 'dark');
  applyLang(currentLang);
  updateCatalogLinks();
  initTouch();
  showLanguage();
  setTimeout(() => requestReveal(true), 120);
}

document.querySelectorAll('[data-select-lang]').forEach(btn => btn.addEventListener('click', () => enter(btn.dataset.selectLang)));
changeLang.addEventListener('click', showLanguage);
themeToggle.addEventListener('click', () => applyTheme(body.classList.contains('theme-light') ? 'dark' : 'light'));
burger.addEventListener('click', () => {
  nav.classList.toggle('open');
  burger.classList.toggle('open');
});
nav.querySelectorAll('a').forEach(a => a.addEventListener('click', closeMenu));
document.addEventListener('click', e => {
  if(!nav.contains(e.target) && !burger.contains(e.target)) closeMenu();
});
window.addEventListener('scroll', () => requestReveal(false), {passive:true});
window.addEventListener('resize', () => { closeMenu(); requestReveal(true); }, {passive:true});
window.addEventListener('orientationchange', () => setTimeout(() => requestReveal(true), 260));
window.addEventListener('pageshow', () => {
  showLanguage();
  requestReveal(true);
});

init();
